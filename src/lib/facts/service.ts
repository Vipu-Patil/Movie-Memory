import { randomUUID } from "node:crypto";
import type { FactRecord, FactStore } from "./store";

/** A fact younger than this is served from cache. */
export const CACHE_WINDOW_MS = 60_000;

/**
 * How long a generation lease lives if its holder never releases it (crash,
 * killed process). Must be comfortably longer than the OpenAI timeout (10s)
 * so a healthy holder never loses its lease mid-flight.
 */
export const LOCK_TTL_MS = 30_000;

/** How long a request waits for another request's in-flight generation. */
export const WAIT_TIMEOUT_MS = 12_000;
export const WAIT_POLL_MS = 250;

export type FactSource =
  /** Served from the 60-second cache. */
  | "cache"
  /** Freshly generated by this request. */
  | "generated"
  /** Generation failed or timed out; this is the most recent older fact. */
  | "stale";

export type FactResult = {
  fact: FactRecord;
  source: FactSource;
  /** When the cache window for this fact ends (a new fact can be generated). */
  cachedUntil: Date;
};

/** The user has not picked a favorite movie yet. */
export class NoFavoriteMovieError extends Error {
  constructor() {
    super("No favorite movie set.");
    this.name = "NoFavoriteMovieError";
  }
}

/** Generation failed and there is no earlier fact to fall back to. */
export class FactUnavailableError extends Error {
  constructor(options?: ErrorOptions) {
    super("Could not generate a fact.", options);
    this.name = "FactUnavailableError";
  }
}

export type FactServiceDeps = {
  store: FactStore;
  /** Calls the LLM. Throws on error/timeout. */
  generate: (movie: string) => Promise<string>;
  /** Injected so tests can control time. */
  now?: () => Date;
  sleep?: (ms: number) => Promise<void>;
  onError?: (error: unknown) => void;
};

export function createFactService(deps: FactServiceDeps) {
  const { store, generate } = deps;
  const now = deps.now ?? (() => new Date());
  const sleep =
    deps.sleep ?? ((ms: number) => new Promise<void>((r) => setTimeout(r, ms)));
  const onError = deps.onError ?? (() => {});

  const isFresh = (fact: FactRecord) =>
    now().getTime() - fact.createdAt.getTime() < CACHE_WINDOW_MS;

  const result = (fact: FactRecord, source: FactSource): FactResult => ({
    fact,
    source,
    cachedUntil: new Date(fact.createdAt.getTime() + CACHE_WINDOW_MS),
  });

  /** Fall back to the newest older fact, or fail with a friendly error. */
  const staleOrThrow = (latest: FactRecord | null, cause?: unknown) => {
    if (latest) return result(latest, "stale");
    throw new FactUnavailableError({ cause });
  };

  /**
   * Return a fact about the user's favorite movie.
   *
   * `userId` must come from the authenticated session, never from client
   * input. Everything below is scoped to it.
   */
  async function getFact(userId: string): Promise<FactResult> {
    const movie = await store.getFavoriteMovie(userId);
    if (!movie) throw new NoFavoriteMovieError();

    // 1. Fast path: the newest fact for this user + movie is still fresh.
    const cached = await store.getLatestFact(userId, movie);
    if (cached && isFresh(cached)) return result(cached, "cache");

    // 2. Need a new fact. Only one request per user may generate at a time.
    const token = randomUUID();
    const acquired = await store.tryAcquireLock(userId, token, LOCK_TTL_MS);

    if (!acquired) {
      // Another tab/refresh is already generating. Wait for its result
      // instead of calling OpenAI a second time.
      return waitForOtherRequest(userId, movie, cached);
    }

    try {
      // 3. Double-check: another request may have finished between our cache
      //    read (step 1) and our lock acquisition (step 2).
      const latest = await store.getLatestFact(userId, movie);
      if (latest && isFresh(latest)) return result(latest, "cache");

      // 4. Call OpenAI. No DB transaction is open here, so a slow call does
      //    not hold a database connection or row locks.
      let content: string;
      try {
        content = await generate(movie);
      } catch (error) {
        onError(error);
        return staleOrThrow(latest, error);
      }

      const fact = await store.createFact({
        userId,
        movie,
        content,
        createdAt: now(),
      });
      return result(fact, "generated");
    } finally {
      // Always release, including on failure, so the next request can retry
      // immediately rather than waiting for the lease to expire.
      await store.releaseLock(userId, token).catch(onError);
    }
  }

  async function waitForOtherRequest(
    userId: string,
    movie: string,
    previous: FactRecord | null,
  ): Promise<FactResult> {
    const deadline = now().getTime() + WAIT_TIMEOUT_MS;

    while (now().getTime() < deadline) {
      await sleep(WAIT_POLL_MS);
      const latest = await store.getLatestFact(userId, movie);
      if (latest && isFresh(latest)) return result(latest, "cache");
    }

    // The other request failed or is very slow. Same fallback as a failure.
    return staleOrThrow(previous);
  }

  return { getFact };
}

export type FactService = ReturnType<typeof createFactService>;
